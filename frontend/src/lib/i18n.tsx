type I18nContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
  status: (value?: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem('ghostwriter_lang') as Lang) || 'ru');
  const value = useMemo<I18nContextValue>(() => {
    const setLang = (next: Lang) => {
      localStorage.setItem('ghostwriter_lang', next);
      setLangState(next);
    };
    const t = (key: string) => dictionaries[lang][key] || key;
    return { lang, setLang, t, status: (status?: string) => (status ? t(`status.${status}`) : '') };
  }, [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
