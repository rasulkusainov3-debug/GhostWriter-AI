DEFAULT_NARRATIVE = (
    "Профессиональное развитие — это не гонка за трендами. "
    "Это последовательное движение в направлении которое соответствует твоим ценностям. "
    "Именно ценности определяют не только карьеру, но и то как тебя воспринимает профессиональное сообщество."
)


def _detect_trend_type(keywords: list[str]) -> str:
    """Определяет тип тренда по ключевым словам."""
    kw_str = " ".join(keywords).lower()
    for t in ["salary", "brand", "career", "skills", "linkedin", "negotiation"]:
        if t in kw_str:
            return t if t != "negotiation" else "salary"
    return "default"


def _get_narrative_fallback(slot: dict, profile: dict) -> str:
    """Запасной вариант — словарь нарративов без LLM."""
    sector     = profile.get("sector", "общее").lower()
    keywords   = slot.get("trend", {}).get("keywords", [])
    trend_type = _detect_trend_type(keywords)

    # Ищем подходящий сектор
    for key, narratives in SECTOR_NARRATIVES.items():
        if key in sector or sector in key:
            return narratives.get(trend_type, narratives.get("default", DEFAULT_NARRATIVE))

    return DEFAULT_NARRATIVE


def generate_persona_block(slot: dict, profile: dict) -> str:
    """
    Генерирует блок призмы пользователя.
    LLM → запасной словарь.
    """
    profession  = profile.get("profession", "специалист")
    sector      = profile.get("sector", "общее")
    prof_values = ", ".join(profile.get("prof_values") or profile.get("values", []))
    trend       = slot.get("trend", {})
    topic       = trend.get("topic", slot.get("post_idea", "карьерный рост"))[:80]
    keywords    = ", ".join(trend.get("keywords", [])[:4])

    user_prompt = PERSONA_PROMPT.format(
        profession=profession,
        sector=sector,
        prof_values=prof_values or "профессионализм, развитие, ответственность",
        topic=topic,
        keywords=keywords or topic,
    )

    # Ollama
    try:
        import ollama as ol
        client = ol.Client(host=os.getenv("OLLAMA_HOST", "http://localhost:11434"))
        client.list()
        resp = client.chat(
            model=os.getenv("OLLAMA_MODEL", "mistral"),
            messages=[
                {"role": "system", "content": PERSONA_SYSTEM},
                {"role": "user",   "content": user_prompt},
            ],
            options={"temperature": 0.7, "num_predict": 400},
        )
        result = resp["message"]["content"].strip()
        if result and len(result) > 50:
            print("    🏠 Агент 3 [Ollama] ✅")
            return result
    except Exception:
        pass

    # Groq
    try:
        groq_key = os.getenv("GROQ_API_KEY", "")
        if groq_key:
            from groq import Groq
            resp = Groq(api_key=groq_key).chat.completions.create(
                model="llama-3.1-8b-instant",
                messages=[
                    {"role": "system", "content": PERSONA_SYSTEM},
                    {"role": "user",   "content": user_prompt},
                ],
                max_tokens=400,
                temperature=0.7,
            )
            result = resp.choices[0].message.content.strip()
            if result and len(result) > 50:
                print("    ⚡ Агент 3 [Groq] ✅")
                return result
    except Exception:
        pass

    # Gemini
    try:
        gemini_key = os.getenv("GEMINI_API_KEY", "")
        if gemini_key:
            import google.generativeai as genai
            genai.configure(api_key=gemini_key)
            model = genai.GenerativeModel("gemini-1.5-flash", system_instruction=PERSONA_SYSTEM)
            result = model.generate_content(user_prompt).text.strip()
            if result and len(result) > 50:
                print("    🌐 Агент 3 [Gemini] ✅")
                return result
    except Exception:
        pass

    # Словарь нарративов
    result = _get_narrative_fallback(slot, profile)
    print("    📖 Агент 3 [словарь] ✅")
    return result
