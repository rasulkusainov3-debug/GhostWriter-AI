# ── Уровень 1: поиск по словарю ───────────────────────────────────────

def infer_from_dict(profession: str) -> dict | None:
    """
    Ищет совпадение в словаре по вхождению ключевого слова в профессию.
    Возвращает инференс или None если не нашёл.
    """
    prof_lower = profession.lower()
    for key, values in PROFESSION_INFERENCE.items():
        if key in prof_lower:
            return values.copy()
    return None


# ── Уровень 2: LLM инференс ───────────────────────────────────────────

INFERENCE_PROMPT = """Пользователь описал свою профессию: "{profession}"

Определи и верни ТОЛЬКО JSON без пояснений:
{{
  "sector": "сфера работы одним словом или фразой",
  "prof_values": ["ценность1", "ценность2", "ценность3", "ценность4"],
  "audience_type": "широкая публика / молодые специалисты / руководители / профессионалы",
  "tone": "экспертный / дружелюбный / провокационный / вдохновляющий / нейтральный",
  "confidence": 0.85
}}"""


def infer_from_llm(profession: str) -> dict:
    """
    Использует LLM для инференса нестандартных профессий.
    Возвращает словарь с confidence или дефолт при ошибке.
    """
    DEFAULT = {
        "sector":       "общее",
        "prof_values":  ["профессионализм", "развитие", "ответственность"],
        "audience_type": "широкая публика",
        "tone":         "экспертный",
        "confidence":   0.5,
    }

    # Пробуем Groq
    try:
        groq_key = os.getenv("GROQ_API_KEY", "")
        if groq_key:
            from groq import Groq
            resp = Groq(api_key=groq_key).chat.completions.create(
                model="llama-3.1-8b-instant",
                messages=[{"role": "user", "content": INFERENCE_PROMPT.format(profession=profession)}],
                max_tokens=300,
                temperature=0.3,
            )
            text = resp.choices[0].message.content.strip()
            # Убираем markdown если LLM добавил
            text = text.replace("```json", "").replace("```", "").strip()
            result = json.loads(text)
            return result
    except Exception as e:
        print(f"  ⚠️  LLM инференс (Groq): {str(e)[:60]}")

    # Пробуем Gemini
    try:
        gemini_key = os.getenv("GEMINI_API_KEY", "")
        if gemini_key:
            import google.generativeai as genai
            genai.configure(api_key=gemini_key)
            model = genai.GenerativeModel("gemini-1.5-flash")
            resp = model.generate_content(INFERENCE_PROMPT.format(profession=profession))
            text = resp.text.strip().replace("```json", "").replace("```", "").strip()
            result = json.loads(text)
            return result
    except Exception as e:
        print(f"  ⚠️  LLM инференс (Gemini): {str(e)[:60]}")

    return DEFAULT


# ── Главная функция ───────────────────────────────────────────────────

def infer_profile(profession: str) -> tuple[dict, str]:
    """
    Основная точка входа.
    Возвращает (inferred_dict, method) где method = 'dict' | 'llm' | 'default'
    """
    # Уровень 1: словарь
    result = infer_from_dict(profession)
    if result:
        result["confidence"] = 0.95
        return result, "dict"

    # Уровень 2: LLM
    result = infer_from_llm(profession)
    method = "llm" if result.get("confidence", 0) >= 0.5 else "default"
    return result, method
